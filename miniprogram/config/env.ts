/**
 * ============================================================================
 * 云开发环境配置 —— 假数据与真实数据的总开关
 * ============================================================================
 *
 * 【这个文件是干什么的】
 * 决定小程序从哪里取数据。现在留空，所以全站走 mock/ 目录下的假数据；
 * 一旦填上云开发环境 ID，就会连真实的云数据库。
 *
 * 【怎么拿到环境 ID】
 * 1. 打开微信开发者工具，点顶部工具栏的「云开发」按钮
 * 2. 首次使用会让你开通，选按量计费的免费额度就够开发用
 * 3. 开通后在「设置 - 环境设置」里能看到「环境 ID」，形如 tennis-3g1a2b3c4d
 * 4. 把它填到下面 CLOUD_ENV_ID 的引号里
 *
 * 【填了之后会发生什么】
 * app.ts 的 initCloud() 会调用 wx.cloud.init() 初始化云能力，
 * globalData.cloudReady 变成 true，页面就可以调用云函数和云数据库了。
 *
 * 【留空会发生什么】
 * 不初始化云开发，USE_MOCK_DATA 为 true，页面继续用假数据。
 * 这样即使没开通云开发，整个小程序也能完整预览，不会白屏或报错。
 *
 * 【注意】
 * 云开发要求基础库 2.2.3 以上。个人主体的 AppID 可以正常使用云开发，
 * 但不能接微信支付（报名收费需要企业主体）。
 */

/** 云开发环境 ID。留空 = 用假数据；填上 = 连云数据库 */
export const CLOUD_ENV_ID = '';

/**
 * 数据来源开关，由上面的环境 ID 自动推导，不需要手动改。
 * 页面里可以这样用：
 *   if (USE_MOCK_DATA) { 用 mock 数据 } else { 调云函数 }
 */
export const USE_MOCK_DATA = !CLOUD_ENV_ID;
